import type { GeoPosition } from '../../vehicles/domain/vehicle.js';
import type { LabeledVehicleRoute } from './labeled-scenarios.js';

/**
 * Manual physical connectivity label, independent of OSM annotation availability.
 * All routes are synthetic, with their intended crossing as points[1].
 * Speed changes occur at integral simulation seconds, starting at atSeconds.
 */
export interface TemporalSpeedChange {
  readonly atSeconds: number;
  readonly speedMps: number;
}

export interface TemporalEncounterScenario {
  readonly id: string;
  readonly explanation: string;
  readonly physicalConnectivity: 'AT_GRADE' | 'GRADE_SEPARATED';
  readonly evidence: 'COMPLETE' | 'MISSING_ANNOTATION';
  readonly crossing: GeoPosition;
  readonly ambulance: LabeledVehicleRoute;
  readonly civilian: LabeledVehicleRoute;
  readonly ambulanceSpeedChanges?: readonly TemporalSpeedChange[];
  readonly civilianSpeedChanges?: readonly TemporalSpeedChange[];
}

// Deliberately schematic coordinates; these are NOT verified Newark roads.
const X = { latitude: 39.683, longitude: -75.750 };
const east = { latitude: 39.683, longitude: -75.749 };
const north = { latitude: 39.684, longitude: -75.750 };
const west = (longitude: number): GeoPosition => ({ latitude: 39.683, longitude });
const south = (latitude: number): GeoPosition => ({ latitude, longitude: -75.750 });

const ambulance = (fromLongitude: number, speedMps: number): LabeledVehicleRoute => ({
  speedMps,
  points: [west(fromLongitude), X, east],
  nodeIds: ['101', '102', '103'],
});

const civilian = (
  fromLatitude: number,
  speedMps: number,
  crossNode: string | null = '102',
): LabeledVehicleRoute => ({
  speedMps,
  points: [south(fromLatitude), X, north],
  nodeIds: ['201', crossNode, '203'],
});

